/**
 * Builds the deterministic two-page PBIP used for native review.
 *
 * The canonical sample remains the source of the semantic model, embedded visual, and page
 * definitions. This generator retains only the declared showcase pages and then creates integrity
 * metadata for the resulting project instead of copying a stale canonical manifest.
 */
const fs = require("node:fs");
const path = require("node:path");
const { writeSampleIntegrity } = require("./sample-integrity.cjs");
const { verifySampleResourceParity } = require("./sample-resource-parity.cjs");
const { FOCUSED_PAGE_NAMES } = require("./sample-definition.cjs");

const root = path.resolve(__dirname, "..");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "pbiviz.json"), "utf8"));
const guid = manifest.visual.guid;
const sampleName = "AtlynProfileLensSample";
const sourceRoot = path.join(root, "samples", sampleName);
const targetRoot = path.join(
    root,
    "dist",
    "release",
    `AtlynProfileLensShowcase-${manifest.visual.version}`
);
const reportRoot = path.join(targetRoot, `${sampleName}.Report`);
const pagesRoot = path.join(reportRoot, "definition", "pages");
const packagePath = path.join(
    root,
    "dist",
    `${manifest.visual.name}.${manifest.visual.version}.pbiviz`
);

function readJson(filePath) {
    return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function writeJson(filePath, value) {
    fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`);
}

if (!fs.existsSync(sourceRoot)) {
    throw new Error('Canonical sample is missing; run "npm run sample:pbip" first.');
}
if (!fs.existsSync(packagePath)) {
    throw new Error('Packaged visual is missing; run "npm run package" first.');
}

fs.rmSync(targetRoot, { recursive: true, force: true });
fs.mkdirSync(path.dirname(targetRoot), { recursive: true });
fs.cpSync(sourceRoot, targetRoot, { recursive: true });

for (const entry of fs.readdirSync(pagesRoot, { withFileTypes: true })) {
    if (entry.isDirectory() && !FOCUSED_PAGE_NAMES.includes(entry.name)) {
        fs.rmSync(path.join(pagesRoot, entry.name), { recursive: true, force: true });
    }
}

const pages = readJson(path.join(pagesRoot, "pages.json"));
pages.pageOrder = [...FOCUSED_PAGE_NAMES];
pages.activePageName = FOCUSED_PAGE_NAMES[0];
writeJson(path.join(pagesRoot, "pages.json"), pages);

const pbipPath = path.join(targetRoot, `${sampleName}.pbip`);
const pbip = readJson(pbipPath);
pbip.settings = { enableAutoRecovery: false };
writeJson(pbipPath, pbip);

const reportPlatformPath = path.join(reportRoot, ".platform");
const reportPlatform = readJson(reportPlatformPath);
reportPlatform.metadata.displayName = "Atlyn Profile Lens Showcase";
reportPlatform.config.logicalId = "877e53bf-47ed-4c8d-9ca9-e3f286cb7807";
writeJson(reportPlatformPath, reportPlatform);

const modelPlatformPath = path.join(
    targetRoot,
    `${sampleName}.SemanticModel`,
    ".platform"
);
const modelPlatform = readJson(modelPlatformPath);
modelPlatform.metadata.displayName = "Atlyn Profile Lens Showcase";
modelPlatform.config.logicalId = "60abebcf-497f-444b-b20e-693ac2472e8b";
writeJson(modelPlatformPath, modelPlatform);

fs.writeFileSync(path.join(targetRoot, "README.md"), `# Atlyn Profile Lens focused PBIP showcase

Generated by \`npm run sample:focused\` from the canonical offline sample and exact packaged
Atlyn Profile Lens ${manifest.visual.version} visual.

1. **World lens showcase** — the active World 50m focus-lens hero with complete country coverage.
2. **USA Counties lens** — all 3,235 packaged counties and equivalents have deterministic synthetic
   profiles, so every county reached by the center probe updates the graph.

The project is offline-only, uses no external data source, and contains only synthetic DAX
\`DATATABLE\` values. Open \`${sampleName}.pbip\` in Power BI Desktop. This generator does not
produce or claim a PBIX.
`);

const expectedPages = new Set([...FOCUSED_PAGE_NAMES, "pages.json"]);
const actualPages = fs.readdirSync(pagesRoot).sort();
if (
    actualPages.length !== expectedPages.size
    || actualPages.some((entry) => !expectedPages.has(entry))
) {
    throw new Error(`Focused sample page set is invalid: ${actualPages.join(", ")}`);
}

const visualDefinitions = [];
for (const pageName of FOCUSED_PAGE_NAMES) {
    const visualsRoot = path.join(pagesRoot, pageName, "visuals");
    for (const visualName of fs.readdirSync(visualsRoot).sort()) {
        const visualPath = path.join(visualsRoot, visualName, "visual.json");
        const visual = readJson(visualPath);
        if (visual.visual?.visualType !== guid) {
            throw new Error(`Focused sample visual does not reference ${guid}: ${visualPath}`);
        }
        visualDefinitions.push(path.relative(targetRoot, visualPath));
    }
}
if (visualDefinitions.length !== 2) {
    throw new Error(`Focused sample must contain exactly two visual definitions, found ${visualDefinitions.length}.`);
}

(async () => {
    const parity = await verifySampleResourceParity({
        packagePath,
        sampleRoot: targetRoot,
        guid
    });
    const integrity = writeSampleIntegrity({
        root,
        sampleRoot: targetRoot,
        generatorPath: __filename,
        definitionPath: path.join(root, "scripts", "sample-definition.cjs"),
        guid
    });
    console.log(`Focused sample PBIP written to ${path.relative(root, targetRoot)}.`);
    console.log(`Focused sample tree SHA-256: ${integrity.projectTree.sha256}`);
    console.log(`Embedded resource SHA-256: ${parity.payload.sha256} (${parity.payload.bytes} bytes).`);
})().catch((error) => {
    console.error(error.message ?? error);
    process.exitCode = 1;
});
